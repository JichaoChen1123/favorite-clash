import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root));
const compile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const musclesUrl = 'data:text/javascript;base64,' + Buffer.from(compile(await read('src/muscles.ts').then(x => x.toString()))).toString('base64');
const { MUSCLES, muscleForName } = await import(musclesUrl);
const navigationCode = compile(await read('src/navigation.ts').then(x => x.toString())).replace("'./muscles'", JSON.stringify(musclesUrl));
const { readAppRoute } = await import('data:text/javascript;base64,' + Buffer.from(navigationCode).toString('base64'));
const asset = await read('public/models/ecorche/ecorche.meshopt.glb');
assert.equal(asset.readUInt32LE(0), 0x46546c67);
assert.equal(asset.readUInt32LE(4), 2);
assert.equal(asset.readUInt32LE(8), asset.length);
const gltf = JSON.parse(asset.subarray(20, 20 + asset.readUInt32LE(12)).toString());
const surface = gltf.nodes.filter(node => node.extras?.layer === 'superficial muscles');
const counts = Object.fromEntries(MUSCLES.map(group => [group.id, surface.filter(node => muscleForName(node.extras.name) === group.id).length]));
assert.ok(Object.values(counts).every(count => count >= 2), 'Every selectable group must have real left/right meshes.');
assert.equal(muscleForName('Long head of left biceps brachii'), 'biceps');
assert.equal(muscleForName('Long head of left biceps femoris'), 'hamstrings');
assert.equal(muscleForName('Left sternocleidomastoid'), null);
assert.deepEqual(readAppRoute('?view=muscles&muscle=chest'), {view:'muscles',jobId:null,muscle:'chest'});
assert.deepEqual(readAppRoute('?view=muscles&muscle=not-a-muscle'), {view:'muscles',jobId:null,muscle:null});
assert.deepEqual(readAppRoute('?job=known&view=muscles&muscle=chest'), {view:'job',jobId:'known',muscle:null});
assert.equal(readAppRoute('?view=compare').view, 'new');
assert.equal(readAppRoute('?view=history').view, 'history');
const manifest = JSON.parse(await readFile(new URL('../docs/ANATOMY_ASSET.json', root), 'utf8'));
const expected = manifest.files.find(file => file.source === 'model/ecorche.meshopt.glb').sha256;
assert.equal(createHash('sha256').update(asset).digest('hex'), expected);
console.log(JSON.stringify({status:'passed',groups:MUSCLES.length,surfaceMeshes:surface.length,counts,assetBytes:asset.length,assetHashMatches:true,routes:'passed'}));
