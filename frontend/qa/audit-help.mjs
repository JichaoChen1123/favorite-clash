// Disposable server only: test help without changing real records or using models.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2]; assert.equal(new URL(base).hostname, '127.0.0.1'); assert.equal(new URL(base).port, '8790');
const out = new URL('../../.runtime/help-qa/', import.meta.url); await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const cases = [], errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 960 } });
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  const requests = [];
  await page.route('**/api/**', route => {
    requests.push({ method: route.request().method(), path: new URL(route.request().url()).pathname });
    if (route.request().method() !== 'GET') return route.fulfill({ status: 403, json: { detail: 'Help QA blocks page mutations' } });
    return route.continue();
  });
  const button = name => page.getByRole('button', { name, exact: true });
  const open = async () => { await button('帮助与使用说明').click(); await page.getByRole('dialog', { name: '帮助与使用说明', exact: true }).waitFor(); };
  const dialog = () => page.getByRole('dialog', { name: '帮助与使用说明', exact: true });
  const noOverflow = async () => {
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await dialog().evaluate(node => node.scrollWidth <= node.clientWidth), true);
  };
  await page.goto(base + '/?view=compare'); await page.waitForLoadState('networkidle');
  const sourceText = 'https://www.bilibili.com/video/BV1ww411f7GV/';
  await page.getByLabel('视频 1', { exact: true }).fill(sourceText);
  await page.getByLabel('你想弄清楚什么？', { exact: true }).fill('未提交的视频问题，打开帮助后保留');
  const initialRequests = requests.length;
  await open(); assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
  assert.equal(await dialog().locator('.help-entry').count(), 21);
  await dialog().getByRole('button', { name: '视频对照', exact: true }).click();
  await dialog().getByRole('searchbox', { name: '搜索帮助', exact: true }).fill('quota');
  assert.equal(await dialog().locator('.help-entry').count(), 1);
  await dialog().locator('summary').click();
  assert.ok((await dialog().innerText()).includes('重启也不会自动恢复'));
  assert.equal(requests.length, initialRequests);
  assert.equal(await dialog().getByRole('link', { name: '完整部署与使用说明 ↗', exact: true }).getAttribute('href'), 'https://github.com/JichaoChen1123/favorite-clash#readme');
  assert.equal(await dialog().getByRole('link', { name: '查看与反馈问题 ↗', exact: true }).getAttribute('href'), 'https://github.com/JichaoChen1123/favorite-clash/issues');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0); assert.equal(await page.evaluate(() => document.body.style.overflow), '');
  assert.equal(await page.getByLabel('视频 1', { exact: true }).inputValue(), sourceText);
  assert.equal(await page.getByLabel('你想弄清楚什么？', { exact: true }).inputValue(), '未提交的视频问题，打开帮助后保留');
  assert.equal(new URL(page.url()).search, '?view=compare');
  assert.equal(await button('帮助与使用说明').evaluate(node => node === document.activeElement), true);
  cases.push('Desktop help searches locally, preserves video draft and URL, restores focus and body scroll on Escape');
  await button('收起侧栏').click(); await open(); await noOverflow();
  await page.screenshot({ path: new URL('desktop.png', out).pathname.replace(/^\/(.:)/, '$1') });
  await dialog().getByRole('button', { name: '关闭帮助', exact: true }).click();
  cases.push('Collapsed desktop sidebar retains an accessible help entry');
  await page.setViewportSize({ width: 390, height: 844 }); await open();
  await dialog().getByRole('searchbox', { name: '搜索帮助', exact: true }).fill('没有对应说明的搜索');
  assert.equal(await dialog().locator('.help-entry').count(), 0);
  await dialog().getByRole('button', { name: '查看全部帮助', exact: true }).click(); assert.equal(await dialog().locator('.help-entry').count(), 21);
  await dialog().getByRole('button', { name: '训练记录', exact: true }).click();
  assert.equal(await dialog().locator('.help-entry').count(), 4);
  const save = dialog().locator('details').filter({ hasText: '保存失败、保存未确认或提示版本冲突怎么办？' }); await save.locator('summary').click();
  await noOverflow(); await page.screenshot({ path: new URL('mobile-390.png', out).pathname.replace(/^\/(.:)/, '$1') });
  await page.setViewportSize({ width: 360, height: 800 }); await noOverflow();
  await dialog().locator('.help-scroll').evaluate(node => node.scrollTop = node.scrollHeight);
  assert.ok(await dialog().locator('.help-scroll').evaluate(node => node.scrollTop > 0));
  await dialog().getByRole('button', { name: '关闭帮助', exact: true }).click();
  assert.equal(await page.getByLabel('视频 1', { exact: true }).inputValue(), sourceText);
  assert.equal(await page.locator('.workspace-bottom-nav button').count(), 4);
  cases.push('390/360 mobile help scrolls internally, supports empty search reset and categories without adding a fifth menu');
  const previous = await (await context.request.get(base + '/api/training')).json();
  if (previous.active) { const record = previous.active; assert.equal((await context.request.put(base + '/api/training/' + record.id, { data: { version: record.version, status: 'cancelled', exercises: record.exercises.map(x => ({ exercise_id: x.exercise_id, sets: x.sets })) } })).status(), 200); }
  const created = await context.request.post(base + '/api/training', { data: { id: randomUUID(), exercise_ids: ['dumbbell-chest-press'] } }); assert.equal(created.status(), 201);
  await page.goto(base + '/?view=training');
  const weight = page.getByRole('textbox', { name: /哑铃卧推第1组重量/ });
  await weight.fill('7.5');
  await button('开始计时').click();
  const clockBefore = await page.evaluate(() => JSON.parse(localStorage.getItem('training-rest-clock')));
  await open(); await dialog().getByRole('button', { name: '训练记录', exact: true }).click();
  await page.waitForTimeout(1100);
  await dialog().getByRole('button', { name: '关闭帮助', exact: true }).click();
  assert.equal(await weight.inputValue(), '7.5');
  const clockAfter = await page.evaluate(() => JSON.parse(localStorage.getItem('training-rest-clock')));
  assert.deepEqual(clockAfter, clockBefore);
  assert.equal(clockAfter.mode, 'running');
  await page.waitForFunction(() => { const text = document.querySelector('.rest-timer-time')?.textContent; return text && text !== '0:00' && text !== '1:30'; }, null, { timeout: 5000 });
  assert.equal(new URL(page.url()).search, '?view=training');
  cases.push('Help does not unmount unsaved training inputs or reset the running rest timer');
  assert.deepEqual(errors, []); assert.equal(requests.filter(r => r.method !== 'GET').length, 0);
  const report = { status: 'passed', cases, realModelRequests: 0, browserMutations: 0, trainingFixtureCreatedOnlyInDisposableDatabase: true, physicalPhoneNotRetested: true };
  await writeFile(new URL('report.json', out), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} finally { await browser.close(); }
