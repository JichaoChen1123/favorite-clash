export function findHelp(category: HelpCategory, query: string): HelpEntry[] {
  const tokens = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return HELP_ENTRIES.filter(entry => {
    if (category !== '全部' && entry.category !== category) return false;
    const text = [entry.category, entry.title, entry.keywords, ...entry.paragraphs, ...(entry.steps || [])].join(' ').toLocaleLowerCase();
    return tokens.every(token => text.includes(token));
  });
}
